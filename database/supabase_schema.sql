-- Extensiones recomendadas en Supabase
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- TABLAS PRINCIPALES (10 TABLAS RELACIONADAS)
-- =============================================================================

-- 1. ROLES
CREATE TABLE IF NOT EXISTS public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    descripcion VARCHAR(200),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. USUARIOS
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id BIGINT NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. CLIENTES
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(180) NOT NULL,
    identificacion_fiscal VARCHAR(30) NOT NULL UNIQUE,
    correo_contacto VARCHAR(160),
    telefono VARCHAR(30),
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'AUDITORIA', 'RENOVACION', 'INACTIVO')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. SEDES
CREATE TABLE IF NOT EXISTS public.sedes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
    nombre VARCHAR(120) NOT NULL,
    direccion VARCHAR(250) NOT NULL,
    contacto VARCHAR(120),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. SLA (Acuerdos de Nivel de Servicio)
CREATE TABLE IF NOT EXISTS public.sla (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('P1', 'P2', 'P3')),
    horas_respuesta NUMERIC(5,2) NOT NULL CHECK (horas_respuesta > 0),
    horas_resolucion NUMERIC(5,2) NOT NULL CHECK (horas_resolucion > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 6. TICKETS (Incidentes y Requerimientos)
CREATE TABLE IF NOT EXISTS public.tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
    sede_id BIGINT REFERENCES public.sedes(id) ON DELETE SET NULL,
    creado_por BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    asignado_a BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
    sla_id BIGINT REFERENCES public.sla(id) ON DELETE SET NULL,
    tipo_requerimiento VARCHAR(50) NOT NULL,
    prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('P1', 'P2', 'P3')),
    estado VARCHAR(25) NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO', 'EN_PROCESO', 'ESPERA', 'RESUELTO', 'CERRADO')),
    asunto VARCHAR(180) NOT NULL,
    descripcion TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    cerrado_en TIMESTAMPTZ
);

-- 7. ORDENES DE TRABAJO
CREATE TABLE IF NOT EXISTS public.ordenes_trabajo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT REFERENCES public.tickets(id) ON DELETE SET NULL,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
    tecnico_id BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
    equipo VARCHAR(160),
    serial_equipo VARCHAR(100),
    prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('P1', 'P2', 'P3')),
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'DIAGNOSTICO', 'COMPLETADA', 'CANCELADA')),
    diagnostico TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. INVENTARIO
CREATE TABLE IF NOT EXISTS public.inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(180) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    precio_unitario NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (precio_unitario >= 0),
    ubicacion VARCHAR(100),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. MOVIMIENTOS DE INVENTARIO
CREATE TABLE IF NOT EXISTS public.movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventario_id BIGINT NOT NULL REFERENCES public.inventario(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    motivo VARCHAR(250) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. BITÁCORA DE TICKETS
CREATE TABLE IF NOT EXISTS public.bitacora_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    comentario TEXT NOT NULL,
    estado_nuevo VARCHAR(25),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

