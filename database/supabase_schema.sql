-- =============================================================================
-- TRIGGERS DE FECHA AUTOMÁTICA
-- =============================================================================
CREATE OR REPLACE FUNCTION public.fn_update_actualizado_en()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_tickets_actualizado_en ON public.tickets;
CREATE TRIGGER trg_tickets_actualizado_en
    BEFORE UPDATE ON public.tickets
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_update_actualizado_en();

DROP TRIGGER IF EXISTS trg_ordenes_actualizado_en ON public.ordenes_trabajo;
CREATE TRIGGER trg_ordenes_actualizado_en
    BEFORE UPDATE ON public.ordenes_trabajo
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_update_actualizado_en();

-- =============================================================================
-- VISTA PARA DASHBOARD / TELEMETRÍA
-- =============================================================================
CREATE OR REPLACE VIEW public.vw_telemetria_resumen AS
SELECT
    (SELECT COUNT(*) FROM public.tickets WHERE estado NOT IN ('CERRADO', 'RESUELTO')) AS tickets_abiertos,
    (SELECT COUNT(*) FROM public.ordenes_trabajo WHERE estado NOT IN ('COMPLETADA', 'CANCELADA')) AS ordenes_activas,
    (SELECT COUNT(*) FROM public.inventario WHERE activo = TRUE AND stock <= stock_minimo) AS stock_critico,
    (SELECT COUNT(*) FROM public.clientes WHERE estado = 'ACTIVO') AS clientes_activos;

